using JetBrains.Annotations;
using LINGYUN.Abp.WeChat.Work.Common.Members.Models;
using LINGYUN.Abp.WeChat.Work.Contacts.Members.Models;
using Newtonsoft.Json;
using System;
using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using Volo.Abp;

namespace LINGYUN.Abp.WeChat.Work.Contacts.Members.Request;
/// <summary>
/// Update member request parameters
/// </summary>
/// <remarks>
/// For details, see: <see href="https://developer.work.weixin.qq.com/document/path/90197" />
/// </remarks>
public class WeChatWorkUpdateMemberRequest : WeChatWorkRequest
{
    /// <summary>
    /// Member UserID. The account corresponding to the management end must be unique within the enterprise. Case-insensitive, length 1~64 bytes
    /// </summary>
    [NotNull]
    [JsonProperty("userid")]
    [JsonPropertyName("userid")]
    [StringLength(64, MinimumLength = 1)]
    public string UserId { get; set; }
    /// <summary>
    /// If the userid is automatically generated by the system, it is only allowed to be modified once. The new value can be specified by the new_userid field.
    /// </summary>
    [CanBeNull]
    [JsonProperty("new_userid")]
    [JsonPropertyName("new_userid")]
    [StringLength(64, MinimumLength = 1)]
    public string? NewUserId { get; set; }
    /// <summary>
    /// Member name. The length is 1~64 utf8 characters
    /// </summary>
    [NotNull]
    [JsonProperty("name")]
    [JsonPropertyName("name")]
    [StringLength(64, MinimumLength = 1)]
    public string Name { get; set; }
    /// <summary>
    /// Member alias. Length 1~64 utf8 characters
    /// </summary>
    [CanBeNull]
    [JsonProperty("alias")]
    [JsonPropertyName("alias")]
    [StringLength(64, MinimumLength = 1)]
    public string? Alias { get; set; }
    /// <summary>
    /// Mobile phone number. Must be unique within the enterprise. If the member has activated Enterprise WeChat, the member needs to modify it by himself (in this case, this parameter is ignored, but no error will be reported). The mobile phone number in mainland China can omit "+86", and the international code must be included in other countries or regions.
    /// </summary>
    [CanBeNull]
    [JsonProperty("mobile")]
    [JsonPropertyName("mobile")]
    public string? Mobile { get; set; }
    /// <summary>
    /// List of department IDs to which members belong, no more than 100
    /// </summary>
    [CanBeNull]
    [JsonProperty("department")]
    [JsonPropertyName("department")]
    public int[]? Department { get; set; }
    /// <summary>
    /// The sorting value within the department, the default is 0. Valid when there is an incoming department. The quantity must be consistent with the department. The larger the value, the higher the order. Valid value range is [0, 2^32)
    /// </summary>
    [CanBeNull]
    [JsonProperty("order")]
    [JsonPropertyName("order")]
    public int[]? Order { get; set; }
    /// <summary>
    /// Job information. The length is 0~128 utf8 characters
    /// </summary>
    [CanBeNull]
    [StringLength(128)]
    [JsonProperty("position")]
    [JsonPropertyName("position")]
    public string? Position { get; set; }
    /// <summary>
    /// Gender
    /// </summary>
    [CanBeNull]
    [JsonProperty("gender")]
    [JsonPropertyName("gender")]
    [Newtonsoft.Json.JsonConverter(typeof(Newtonsoft.Json.EnumToNumberStringConverter<Gender>))]
    [System.Text.Json.Serialization.JsonConverter(typeof(System.Text.Json.Serialization.EnumToNumberStringConverter<Gender>))]
    public Gender? Gender { get; set; }
    /// <summary>
    /// Email. You can fill in the company's existing email account to facilitate colleagues to obtain members' email accounts to send emails. The length is 6~64 bytes and is a valid email format. Must be unique within the enterprise. Overseas members can use this email address to log in to corporate WeChat.
    /// </summary>
    [CanBeNull]
    [StringLength(64)]
    [JsonProperty("email")]
    [JsonPropertyName("email")]
    public string? Email { get; set; }
    /// <summary>
    /// If the enterprise has opened Tencent Enterprise Email (Enterprise WeChat Email), setting this value can create an enterprise email account. The length is 6~63 bytes and is in a valid corporate email format. Must be unique within the enterprise. If not filled in, the system will generate a default corporate email for the user (the email generated by the system can be modified once).
    /// </summary>
    [CanBeNull]
    [StringLength(64)]
    [JsonProperty("biz_mail")]
    [JsonPropertyName("biz_mail")]
    public string? BizEmail { get; set; }
    /// <summary>
    /// Business email alias. The length is 6~63 bytes and is in a valid corporate email format. It must be unique within the enterprise, and up to 5 aliases can be set. The update is an overlay update. Passing an empty structure or array will clear the current corporate email alias.
    /// </summary>
    [CanBeNull]
    [StringLength(63, MinimumLength = 6)]
    [JsonProperty("biz_mail_alias")]
    [JsonPropertyName("biz_mail_alias")]
    public string? BizEmailAlias { get; set; }
    /// <summary>
    /// Landline. Within 32 bytes, it consists of pure numbers, "-", "+" or ",".
    /// </summary>
    [CanBeNull]
    [StringLength(32)]
    [JsonProperty("telephone")]
    [JsonPropertyName("telephone")]
    public string? TelePhone { get; set; }
    /// <summary>
    /// Department head field, the number must be consistent with department, indicating whether the department is the person in charge. 0-no, 1-yes
    /// </summary>
    [CanBeNull]
    [JsonProperty("is_leader_in_dept")]
    [JsonPropertyName("is_leader_in_dept")]
    public int[]? IsLeaderInDept { get; set; }
    /// <summary>
    /// Direct superior UserID, the setting scope is members within the enterprise, and up to 1 superior can be set
    /// </summary>
    [CanBeNull]
    [JsonProperty("direct_leader")]
    [JsonPropertyName("direct_leader")]
    public string[]? DirectLeader { get; set; }
    /// <summary>
    /// The mediaid of the member's avatar, which is obtained by uploading pictures through the material management interface.
    /// </summary>
    [CanBeNull]
    [JsonProperty("avatar_mediaid")]
    [JsonPropertyName("avatar_mediaid")]
    public string? AvatarMediaId { get; set; }
    /// <summary>
    /// Enable/disable members. 1 means enable the member, 0 means disable the member
    /// </summary>
    [CanBeNull]
    [JsonProperty("enable")]
    [JsonPropertyName("enable")]
    public int? Enable { get; set; }
    /// <summary>
    /// Extended attributes. The extended attribute field needs to be added on the WEB management side first, see the extended attribute adding method, otherwise the assignment of unknown attributes will be ignored. For field details, see member extended attributes
    /// </summary>
    [CanBeNull]
    [JsonProperty("extattr")]
    [JsonPropertyName("extattr")]
    public MemberExternalAttribute? ExternalAttribute { get; set; }
    /// <summary>
    /// External attributes of members, please see external attributes for field details
    /// </summary>
    [CanBeNull]
    [JsonProperty("external_profile")]
    [JsonPropertyName("external_profile")]
    public ExternalProfile? ExternalProfile { get; set; }
    /// <summary>
    /// External position, if this value is set, this will be used as the position displayed externally, otherwise it will be displayed as position. No more than 12 Chinese characters
    /// </summary>
    [CanBeNull]
    [StringLength(12)]
    [JsonProperty("external_position")]
    [JsonPropertyName("external_position")]
    public string? ExternalPosition { get; set; }
    /// <summary>
    /// Video account name (after setting, members will display the video account to the outside world). You must choose from the video accounts bound to the enterprise WeChat account. You can view the bound video accounts on the "My Enterprise" page.
    /// </summary>
    [CanBeNull]
    [JsonProperty("nickname")]
    [JsonPropertyName("nickname")]
    public string? NickName { get; set; }
    /// <summary>
    /// Address. Maximum length 128 characters
    /// </summary>
    [CanBeNull]
    [StringLength(128)]
    [JsonProperty("address")]
    [JsonPropertyName("address")]
    public string? Address { get; set; }
    /// <summary>
    /// Main department
    /// </summary>
    [CanBeNull]
    [JsonProperty("main_department")]
    [JsonPropertyName("main_department")]
    public int? MainDepartment { get; set; }

    public WeChatWorkUpdateMemberRequest(
        string userId,
        string name)
    {
        UserId = userId;
        Name = name;
    }

    protected override void Validate()
    {
        Check.NotNullOrWhiteSpace(UserId, nameof(UserId), 64, 1);
        Check.NotNullOrWhiteSpace(Name, nameof(Name), 64, 1);
        Check.Length(Alias, nameof(Alias), 64, 1);
        Check.Length(Position, nameof(Position), 128);
        Check.Length(Email, nameof(Email), 64, 6);
        Check.Length(BizEmail, nameof(BizEmail), 64, 6);
        Check.Length(TelePhone, nameof(TelePhone), 32);
        Check.Length(ExternalPosition, nameof(ExternalPosition), 12);
        Check.Length(Address, nameof(Address), 128);
        Check.Length(NewUserId, nameof(NewUserId), 64, 1);
        // List of department IDs to which members belong, no more than 100
        if (Department?.Length > 0)
        {
            // List of department IDs to which members belong, no more than 100
            if (Department?.Length > 100)
            {
                throw new ArgumentException("The list of department ids to which members belong shall not exceed 100!");
            }
            // The number of department sorting lists must be consistent with the number of parameter department
            if (Order?.Length != Department?.Length)
            {
                throw new ArgumentException("The number of Order must be consistent with the number of the parameter \"department\"!");
            }
            // The number of department heads list must be consistent with the number of parameter department
            if (IsLeaderInDept?.Length != Department?.Length)
            {
                throw new ArgumentException("The number of IsLeaderInDept must be consistent with the number of the parameter \"Department\"!");
            }
        }
        // Only one direct superior can be set at most
        if (DirectLeader?.Length > 1)
        {
            throw new ArgumentException("At most, only one direct superior can be set up!");
        }
        // Only two values can exist
        if (Enable.HasValue && Enable != 0)
        {
            Enable = 1;
        }
    }
}
