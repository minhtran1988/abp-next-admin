using System;
using Volo.Abp.Auditing;
using Volo.Abp.Data;

namespace LINGYUN.Abp.IM.Messages;

/// <summary>
/// Last communication message
/// </summary>
public class LastChatMessage : IHasExtraProperties
{
    public string? AvatarUrl { get; set; }

    public string? Object { get; set; }
    /// <summary>
    /// Tenant
    /// </summary>
    public Guid? TenantId { get; set; }
    /// <summary>
    /// Group ID
    /// </summary>
    public string GroupId { get; set; } = default!;
    /// <summary>
    /// Message ID
    /// </summary>
    /// <remarks>
    /// The caller does not need to pay attention to this field, it will be automatically generated by the service
    /// </remarks>
    public string MessageId { get; set; } = default!;
    /// <summary>
    /// Sender ID
    /// </summary>
    public Guid FormUserId { get; set; }
    /// <summary>
    /// Sender name
    /// </summary>
    public string FormUserName { get; set; } = default!;
    /// <summary>
    /// Receive user ID
    /// </summary>
    /// <remarks>
    /// Designed to be nullable for compatibility with group chat messages
    /// /remarks>
    public string ToUserId { get; set; } = default!;
    /// <summary>
    /// Message content
    /// </summary>
    [DisableAuditing]
    public string Content { get; set; } = default!;
    /// <summary>
    /// Sending time
    /// </summary>
    public DateTime SendTime { get; set; }
    /// <summary>
    /// Whether to send anonymously (stored in the extension field)
    /// </summary>
    public bool IsAnonymous => this.GetProperty(nameof(IsAnonymous), false);
    /// <summary>
    /// Message type
    /// </summary>
    public MessageType MessageType { get; set; }

    public MessageSourceType Source { get; set; }
    public ExtraPropertyDictionary ExtraProperties { get; set; }
    public LastChatMessage()
    {
        ExtraProperties = new ExtraPropertyDictionary();
    }
}
