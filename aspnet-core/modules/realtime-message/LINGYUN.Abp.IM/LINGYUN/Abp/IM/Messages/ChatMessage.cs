using LINGYUN.Abp.RealTime.Localization;
using System;
using Volo.Abp.Auditing;
using Volo.Abp.Data;
using Volo.Abp.EventBus;
using Volo.Abp.Timing;

namespace LINGYUN.Abp.IM.Messages;

[Serializable]
[EventName("im.message")]
public class ChatMessage : IHasExtraProperties
{
    /// <summary>
    /// Tenant
    /// </summary>
    public Guid? TenantId { get; set; }
    /// <summary>
    /// Group ID
    /// </summary>
    public string GroupId { get; set; } = default!;
    /// <summary>
    /// Message ID
    /// </summary>
    /// <remarks>
    /// The caller does not need to pay attention to this field, it will be automatically generated by the service
    /// </remarks>
    public string MessageId { get; set; } = default!;
    /// <summary>
    /// Sender ID
    /// </summary>
    public Guid FormUserId { get; set; }
    /// <summary>
    /// Sender name
    /// </summary>
    public string FormUserName { get; set; } = default!;
    /// <summary>
    /// Receive user ID
    /// </summary>
    /// <remarks>
    /// Designed to be nullable for compatibility with group chat messages
    /// /remarks>
    public Guid? ToUserId { get; set; }
    /// <summary>
    /// Message content
    /// </summary>
    [DisableAuditing]
    public string Content { get; set; } = default!;
    /// <summary>
    /// Sending time
    /// </summary>
    public DateTime SendTime { get; set; }
    /// <summary>
    /// Whether to send anonymously (stored in the extension field)
    /// </summary>
    public bool IsAnonymous { get; set; }
    /// <summary>
    /// Message type
    /// </summary>
    public MessageType MessageType { get; set; } = MessageType.Text;

    public MessageSourceType Source { get; set; } = MessageSourceType.User;

    public ExtraPropertyDictionary ExtraProperties { get; set; }

    public ChatMessage()
    {
        ExtraProperties = new ExtraPropertyDictionary();
        this.SetDefaultsForExtraProperties();
    }

    public static ChatMessage User(
        Guid formUserId,
        string formUserName,
        Guid toUserId,
        string content,
        IClock clock,
        bool isAnonymous = false,
        MessageType type = MessageType.Text,
        MessageSourceType souce = MessageSourceType.User,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = formUserName,
            ToUserId = toUserId,
            Content = content,
            SendTime = clock.Now,
            IsAnonymous = isAnonymous,
            MessageType = type,
            TenantId = tenantId,
            Source = souce,
        };
    }
    public static ChatMessage System(
        Guid formUserId,
        Guid toUserId,
        string content,
        IClock clock,
        MessageType type = MessageType.Text,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = "system",
            ToUserId = toUserId,
            Content = content,
            SendTime = clock.Now,
            IsAnonymous = false,
            MessageType = type,
            TenantId = tenantId,
            Source = MessageSourceType.System,
        }
        .SetProperty("L", false);
    }

    /// <summary>
    /// Localized system messages
    /// User messages and group messages cannot use multiple languages
    /// </summary>
    /// <param name="formUserId"></param>
    /// <param name="toUserId"></param>
    /// <param name="content"></param>
    /// <param name="clock"></param>
    /// <param name="type"></param>
    /// <param name="tenantId"></param>
    /// <returns></returns>
    public static ChatMessage SystemLocalized(
        Guid formUserId,
        Guid toUserId,
        LocalizableStringInfo content,
        IClock clock,
        MessageType type = MessageType.Text,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = "system",
            ToUserId = toUserId,
            Content = "",
            SendTime = clock.Now,
            IsAnonymous = false,
            MessageType = type,
            TenantId = tenantId,
            Source = MessageSourceType.System,
        }
        .SetProperty("L", true)
        .SetProperty(nameof(ChatMessage.Content).ToPascalCase(), content);
    }

    public static ChatMessage System(
        Guid formUserId,
        string groupId,
        string content,
        IClock clock,
        MessageType type = MessageType.Text,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = "system",
            GroupId = groupId,
            Content = content,
            SendTime = clock.Now,
            IsAnonymous = false,
            MessageType = type,
            TenantId = tenantId,
            Source = MessageSourceType.System,
        }
        .SetProperty("L", false);
    }
    /// <summary>
    /// Localized system messages
    /// User messages and group messages cannot use multiple languages
    /// </summary>
    /// <param name="formUserId"></param>
    /// <param name="groupId"></param>
    /// <param name="content"></param>
    /// <param name="clock"></param>
    /// <param name="type"></param>
    /// <param name="tenantId"></param>
    /// <returns></returns>
    public static ChatMessage SystemLocalized(
        Guid formUserId,
        string groupId,
        LocalizableStringInfo content,
        IClock clock,
        MessageType type = MessageType.Text,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = "system",
            GroupId = groupId,
            Content = "",
            SendTime = clock.Now,
            IsAnonymous = false,
            MessageType = type,
            TenantId = tenantId,
            Source = MessageSourceType.System,
        }
        .SetProperty("L", true)
        .SetProperty(nameof(ChatMessage.Content).ToPascalCase(), content);
    }

    public static ChatMessage Group(
        Guid formUserId,
        string formUserName,
        string groupId,
        string content,
        IClock clock,
        bool isAnonymous = false,
        MessageType type = MessageType.Text,
        MessageSourceType souce = MessageSourceType.User,
        Guid? tenantId = null)
    {
        return new ChatMessage
        {
            FormUserId = formUserId,
            FormUserName = formUserName,
            GroupId = groupId,
            Content = content,
            SendTime = clock.Now,
            IsAnonymous = isAnonymous,
            MessageType = type,
            TenantId = tenantId,
            Source = souce,
        };
    }
}
