using JetBrains.Annotations;
using System.Collections.Generic;
using Volo.Abp;
using Volo.Abp.Localization;
using Volo.Abp.SimpleStateChecking;

namespace LINGYUN.Abp.AI.Workspaces;
/// <summary>
/// Workspace definition
/// </summary>
public class WorkspaceDefinition : IHasSimpleStateCheckers<WorkspaceDefinition>
{
    /// <summary>
    /// Name
    /// </summary>
    [NotNull]
    public string Name { get; }
    /// <summary>
    /// AI provider name
    /// </summary>
    [NotNull]
    public string Provider { get; }
    /// <summary>
    /// Model name
    /// </summary>
    [NotNull]
    public string ModelName { get; }
    /// <summary>
    /// Display name
    /// </summary>
    [NotNull]
    public ILocalizableString DisplayName {
        get => _displayName;
        set => _displayName = Check.NotNull(value, nameof(value));
    }
    private ILocalizableString _displayName = default!;
    /// <summary>
    /// Description
    /// </summary>
    public ILocalizableString? Description { get; set; }
    /// <summary>
    /// API authentication key
    /// </summary>
    public string? ApiKey { get; private set; }
    /// <summary>
    /// Custom endpoint URL
    /// </summary>
    public string? ApiBaseUrl { get; private set; }
    /// <summary>
    /// System prompt word
    /// </summary>
    public string? SystemPrompt { get; set; }
    /// <summary>
    /// Additional system prompt words
    /// </summary>
    public string? Instructions { get; set; }
    /// <summary>
    /// The temperature value based on which the chat reply is based. If it is empty, the default value is determined by the model provider.
    /// </summary>
    /// <remarks>
    /// The range is between 0 and 2. Higher values (such as 0.8) will make the output more random, while lower values (such as 0.2) will make the output more concentrated and deterministic.
    /// </remarks>
    public float? Temperature {
        get => _temperature;
        set {
            if (value.HasValue)
            {
                _temperature = Check.Range(value.Value, nameof(value), 0, 2);
            }
            else
            {
                _temperature = value;
            }
        }
    }
    private float? _temperature;
    /// <summary>
    /// Limit the maximum number of completion tokens generated by the model in one request
    /// </summary>
    public int? MaxOutputTokens { get; set; }
    /// <summary>
    /// A number between -2.0 and 2.0
    /// </summary>
    /// <remarks>
    /// If the value is positive, the new token will be punished according to its frequency of occurrence in the existing text, reducing the possibility of the model repeating the same content.
    /// </remarks>
    public float? FrequencyPenalty {
        get => _frequencyPenalty;
        set {
            if (value.HasValue)
            {
                _frequencyPenalty = Check.Range(value.Value, nameof(value), -2, 2);
            }
            else
            {
                _frequencyPenalty = value;
            }
        }
    }
    private float? _frequencyPenalty;
    /// <summary>
    /// A number between -2.0 and 2.0
    /// </summary>
    /// <remarks>
    /// If this value is positive, then the new token will be penalized based on whether it has appeared in the existing text, thus increasing the likelihood that the model talks about new topics
    /// </remarks>
    public float? PresencePenalty {
        get => _presencePenalty;
        set {
            if (value.HasValue)
            {
                _presencePenalty = Check.Range(value.Value, nameof(value), -2, 2);
            }
            else
            {
                _presencePenalty = value;
            }
        }
    }
    private float? _presencePenalty;
    /// <summary>
    /// Enable/disable workspace
    /// </summary>
    public bool IsEnabled { get; set; }

    [NotNull]
    public Dictionary<string, object> Properties { get; }

    [NotNull]
    public List<string> Tools { get; }

    public List<ISimpleStateChecker<WorkspaceDefinition>> StateCheckers { get; }

    public WorkspaceDefinition(
        string name, 
        string provider,
        string modelName, 
        ILocalizableString displayName, 
        ILocalizableString? description = null,
        string? systemPrompt = null,
        string? instructions = null,
        float? temperature = null,
        int? maxOutputTokens = null,
        float? frequencyPenalty = null,
        float? presencePenalty = null)
    {
        Name = name;
        Provider = provider;
        ModelName = modelName;
        DisplayName = displayName;
        Description = description;
        SystemPrompt = systemPrompt;
        Instructions = instructions;
        Temperature = temperature;
        MaxOutputTokens = maxOutputTokens;
        FrequencyPenalty = frequencyPenalty;
        PresencePenalty = presencePenalty;

        IsEnabled = true;
        Tools = new List<string>();
        Properties = new Dictionary<string, object>();
        StateCheckers = new List<ISimpleStateChecker<WorkspaceDefinition>>();
    }

    public virtual WorkspaceDefinition WithApiBaseUrl(string apiBaseUrl)
    {
        ApiBaseUrl = apiBaseUrl;
        return this;
    }

    public virtual WorkspaceDefinition WithApiKey(string apiKey)
    {
        ApiKey = apiKey;
        return this;
    }

    public virtual WorkspaceDefinition WithTools(params string[] tools)
    {
        Tools.AddIfNotContains(tools);
        return this;
    }

    public virtual WorkspaceDefinition WithProperty(string key, object value)
    {
        Properties[key] = value;
        return this;
    }

    public override string ToString()
    {
        return $"[{nameof(WorkspaceDefinition)} {Name}]";
    }
}
